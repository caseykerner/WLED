static uint32_t fnv(const std::string& s) {
  uint32_t h = 2166136261u;
  for (unsigned char c : s) { h ^= c; h *= 16777619u; }
  return h;
}

// The same names the app uses for its cloud logins.
static String loginFor(const String& name) {
  String n = name; n.toLowerCase();
  if (n.indexOf("house") >= 0) return "house";
  if (n.indexOf("beer") >= 0) return "beerfridge";
  if (n.indexOf("shop") >= 0) return "shop";
  if (n.indexOf("shed") >= 0) return "shed";
  if (n.indexOf("pergola") >= 0) return "pergola";
  String out;
  for (char c : n) if (isalnum((unsigned char)c)) out += c;
  return out.length() ? out : String("wled");
}

// Index of the controller with this login, and its address (copied), or -1.
static int findCtrl(const String& login, String& ip) {
  int found = -1;
  xSemaphoreTake(ctrlMx, portMAX_DELAY);
  for (int i = 0; i < nCtrls; i++) if (ctrls[i].login == login && !ctrls[i].direct) { found = i; ip = ctrls[i].ip; break; }
  xSemaphoreGive(ctrlMx);
  return found;
}

