static const char* resetName(esp_reset_reason_t r) {
  switch (r) {
    case ESP_RST_POWERON: return "power on";
    case ESP_RST_SW: return "software restart";
    case ESP_RST_PANIC: return "crash";
    case ESP_RST_INT_WDT: case ESP_RST_TASK_WDT: case ESP_RST_WDT: return "watchdog";
    case ESP_RST_BROWNOUT: return "low power (brownout)";
    case ESP_RST_DEEPSLEEP: return "wake from sleep";
    case ESP_RST_EXT: return "reset pin";
    default: return "unknown";
  }
}

void setup() {
  Serial.begin(115200);
  resetReason = resetName(esp_reset_reason());
  if (esp_reset_reason() == ESP_RST_PANIC || esp_reset_reason() == ESP_RST_TASK_WDT || esp_reset_reason() == ESP_RST_INT_WDT) lastCrashStage = crashStage;
  crashStage = 0;
  powerOnWindow = esp_reset_reason() == ESP_RST_POWERON || esp_reset_reason() == ESP_RST_EXT;
  if (psramFound() && ESP.getPsramSize() > 0) mbedtls_platform_set_calloc_free(tlsCalloc, tlsFree);
  led(0, 0, 40);
  LittleFS.begin(true);
  provisioned = loadCloud();
  loadOwned();
  loadKnown();
  stateTopicSelf = String("hg/") + (cloudId.length() ? cloudId : String("bridge")) + "/state";
  ctrlMx = xSemaphoreCreateMutex();
  jobQ = xQueueCreate(32, sizeof(Job*));
  outQ = xQueueCreate(48, sizeof(Out*));
  hubQ = xQueueCreate(8, sizeof(std::string*));

  // Wi-Fi: the network saved by Bluetooth setup (or by the older setup portal). With none saved, or
  // one that stops working, Bluetooth setup turns on (bleManage) and the hub keeps trying meanwhile.
  loadSetupCode();
  bleQ = xQueueCreate(4, sizeof(std::string*));
  xTaskCreatePinnedToCore(setupTask, "hgSetup", 8192, nullptr, 1, nullptr, 0);
  WiFi.mode(WIFI_STA);
  WiFi.setHostname("homeglow-bridge");
  WiFi.setAutoReconnect(true);
  WiFi.setSleep(false);
  led(40, 30, 0);
  if (!savedSsid().isEmpty()) { Serial.println("[wifi] joining " + savedSsid()); WiFi.begin(); }
  else Serial.println("[wifi] nothing saved: waiting for Bluetooth setup");

  // The bridge checks the cloud's certificate against Amazon Root CA 1 only, and logs in with its own.
  if (provisioned) {
    tls.setCACert(cloudCa.c_str());
    tls.setCertificate(cloudCert.c_str());
    tls.setPrivateKey(cloudKey.c_str());
  }
  mqtt.setBufferSize(TUN_PART + 2048);     // in the 8 MB PSRAM
  mqtt.setKeepAlive(60);
  mqtt.setCallback(onMessage);

  web.on("/", webRoot);
  web.on("/json", webStatusJson);
  web.on("/log", webLog);
  web.on("/hub/play", HTTP_POST, webHubPlay);
  web.on("/update", HTTP_POST, webUpdateDone, webUpdateChunk);
  web.on("/provision", HTTP_POST, webProvision);
  web.on("/provision", HTTP_OPTIONS, webCors);
  web.begin();

  // Workers and the status task run on core 0; the main loop (cloud, web page) stays on core 1.
  for (int i = 0; i < WORKERS; i++) xTaskCreatePinnedToCore(workerTask, "hgWork", 10240, nullptr, 1, nullptr, i % 2);
  xTaskCreatePinnedToCore(statusTask, "hgStatus", 10240, nullptr, 1, nullptr, 0);
  xTaskCreatePinnedToCore(hubTask, "hgHub", 24576, nullptr, 1, nullptr, 0);

  if (!provisioned) led(40, 0, 40);   // purple: needs its cloud login (the cloud connects from loop once Wi-Fi is up)
}

void loop() {
  web.handleClient();
  static uint32_t lastBle = 0;
  if (millis() - lastBle > 1000) { lastBle = millis(); bleManage(); }
  if (WiFi.status() != WL_CONNECTED) {
    if (!wifiLostSince) wifiLostSince = millis() | 1;
    // A saved network that's gone quiet: ask again now and then (setAutoReconnect covers most cases).
    static uint32_t lastJoin = 0;
    if (!savedSsid().isEmpty() && millis() - lastJoin > 30000 && millis() - wifiLostSince > 30000) { lastJoin = millis(); WiFi.begin(); }
    if (bleOn) led(0, 25, 40); else led(40, 30, 0);       // cyan: waiting for Bluetooth setup; amber: no Wi-Fi
    delay(50); return;
  }
  wifiLostSince = 0;
  if (!mdnsUp) { mdnsUp = MDNS.begin("homeglow-bridge"); if (mdnsUp) MDNS.addService("http", "tcp", 80); }
  if (!provisioned) { static uint32_t lp = 0; if (millis() - lp > 2000) { lp = millis(); led(40, 0, 40); } }
  if (provisioned) {
    if (!mqtt.connected()) { if (!bleOn && (!lastTry || millis() - lastTry > 15000)) connectCloud(); }
    else mqtt.loop();
  }
  // Publish what the workers and the status task produced (a few per pass keeps the loop lively).
  for (int k = 0; k < 6; k++) {
    Out* o = nullptr;
    if (xQueueReceive(outQ, &o, 0) != pdTRUE || !o) break;
    if (mqtt.connected()) publishOut(*o);
    delete o;
  }
  for (size_t i = 0; i < tunIn.size(); i++)   // parts that never all arrived
    if (millis() - tunIn[i].started > 30000) { tunIn.erase(tunIn.begin() + i); break; }
  delay(2);
}
