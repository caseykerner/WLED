// Reads one controller's state (and its info when due) and publishes what changed:
//  hg/<login>/state  small summary (online, on, bri, ps, pl, heap, up, ver), as before
//  hg/<login>/full   {"state":…,"info":…} exactly as WLED gives them, for the app to show at once
static void poll(int i) {
  Controller& c = ctrls[i];
  c.lastPoll = millis();
  bool soon = c.pollSoon; c.pollSoon = false;
  String ip, login;
  xSemaphoreTake(ctrlMx, portMAX_DELAY); ip = c.ip; login = c.login; xSemaphoreGive(ctrlMx);
  if (ip.isEmpty()) return;
  // A tunnelled request is using the controller: it's clearly alive; check again shortly.
  if (xSemaphoreTake(c.lock, pdMS_TO_TICKS(soon ? 3000 : 200)) != pdTRUE) { c.pollSoon = soon; return; }
  uint32_t cto = c.online ? 2500 : 1200;
  std::string state;
  int code = wledRequest(ip, "GET", "/json/state", "", "", state, nullptr, cto, 3000);
  bool infoDue = code == 200 && (c.info.empty() || millis() - c.lastInfo > INFO_EVERY_MS || !c.online);
  std::string info;
  if (infoDue && wledRequest(ip, "GET", "/json/info", "", "", info, nullptr, cto, 3000) == 200) {
    c.info = info; c.lastInfo = millis();
  }
  xSemaphoreGive(c.lock);

  if (code != 200) {
    if (++c.misses >= 2 && c.online) {
      c.online = false;
      Out* o = new Out; o->topic = ("hg/" + login + "/state").c_str();
      o->payload = "{\"online\":false,\"via\":\"bridge\"}"; o->retained = true; post(o);
      Serial.printf("[poll] %s offline\n", login.c_str());
    }
    return;
  }
  c.misses = 0;
  if (!c.info.empty()) {
    JsonDocument f; f["hgCloud"]["en"] = true;
    JsonDocument d;
    if (!deserializeJson(d, c.info, DeserializationOption::Filter(f))) c.direct = d["hgCloud"]["en"] | false;
  }
  if (c.direct) return;                    // it speaks for itself
  bool was = c.online; c.online = true;
  if (!was) c.onlineSince = millis();
  checkDesired(c, login, state, !was);
  uint32_t h = fnv(state);
  bool changed = h != c.stateHash || !was;
  c.stateHash = h;
  uint32_t now = millis();
  if (changed || infoDue || now - c.lastFull > HEARTBEAT_MS) {
    Out* o = new Out; o->topic = ("hg/" + login + "/full").c_str(); o->retained = true;
    o->payload.reserve(state.size() + c.info.size() + 40);
    o->payload = "{\"state\":"; o->payload += state;
    o->payload += ",\"info\":"; o->payload += c.info.empty() ? "{}" : c.info;
    o->payload += ",\"via\":\"bridge\"}";
    post(o); c.lastFull = now;
  }
  if (changed || infoDue || now - c.lastSmall > HEARTBEAT_MS) {
    JsonDocument fs; fs["on"] = true; fs["bri"] = true; fs["ps"] = true; fs["pl"] = true;
    JsonDocument st; deserializeJson(st, state, DeserializationOption::Filter(fs));
    JsonDocument fi; fi["freeheap"] = true; fi["uptime"] = true; fi["ver"] = true;
    JsonDocument in; deserializeJson(in, c.info, DeserializationOption::Filter(fi));
    JsonDocument s;
    s["online"] = true; s["via"] = "bridge"; s["hub"] = cloudId;
    s["on"] = st["on"] | false; s["bri"] = st["bri"] | 0; s["ps"] = st["ps"] | -1; s["pl"] = st["pl"] | -1;
    s["heap"] = in["freeheap"] | 0; s["up"] = in["uptime"] | 0; s["ver"] = in["ver"] | "";
    Out* o = new Out; o->topic = ("hg/" + login + "/state").c_str(); o->retained = true;
    serializeJson(s, o->payload); post(o); c.lastSmall = now;
  }
  if (!was) Serial.printf("[poll] %s online\n", login.c_str());
}

static void statusTask(void*) {
  for (;;) {
    if (WiFi.status() == WL_CONNECTED) {
      if (millis() - lastScan > SCAN_EVERY_MS || nCtrls == 0) scan();
      // Asked-for checks (after a change) first, then whatever is due.
      int pick = -1;
      for (int i = 0; i < nCtrls && pick < 0; i++) if (ctrls[i].pollSoon) pick = i;
      for (int i = 0; i < nCtrls && pick < 0; i++) {
        uint32_t every = ctrls[i].direct ? INFO_EVERY_MS : (ctrls[i].online ? STATE_EVERY_MS : OFFLINE_EVERY_MS);
        if (millis() - ctrls[i].lastPoll > every) pick = i;
      }
      if (pick >= 0) { poll(pick); delay(5); continue; }
    }
    delay(50);
  }
}

