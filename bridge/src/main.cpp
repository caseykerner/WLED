static uint32_t fnv(const std::string& s) {
  uint32_t h = 2166136261u;
  for (unsigned char c : s) { h ^= c; h *= 16777619u; }
  return h;
}

// The same names the app uses for its cloud logins.
static String loginFor(const String& name) {
  String n = name; n.toLowerCase();
  if (n.indexOf("house") >= 0) return "house";
  if (n.indexOf("beer") >= 0) return "beerfridge";
  if (n.indexOf("shop") >= 0) return "shop";
  if (n.indexOf("shed") >= 0) return "shed";
  if (n.indexOf("pergola") >= 0) return "pergola";
  String out;
  for (char c : n) if (isalnum((unsigned char)c)) out += c;
  return out.length() ? out : String("wled");
}

// Index of the controller with this login, and its address (copied), or -1.
// ---------- which controllers are this hub's ----------
// A hub only looks after the controllers its owner gave it (by hardware address, kept in
// OWNED_FILE), so two hubs on one network (a second hub, a neighbour on shared Wi-Fi) never both
// drive the same controller. The others it finds are only listed, so the app can offer them.
// A hub with no list at all (set up before 0.9) keeps the old behaviour: every controller it finds.
#define OWNED_FILE "/owned.json"
static bool ownedListed = false;
static std::vector<String> ownedMacs;     // guarded by ctrlMx
static bool isOwnedMac(const String& mac) {            // call with ctrlMx held
  if (!ownedListed) return true;
  for (auto& m : ownedMacs) if (m.equalsIgnoreCase(mac)) return true;
  return false;
}
static void loadOwned() {
  File f = LittleFS.open(OWNED_FILE, "r");
  if (!f) return;
  JsonDocument d;
  if (!deserializeJson(d, f)) { ownedListed = true; for (JsonVariant m : d["macs"].as<JsonArray>()) ownedMacs.push_back(m.as<String>()); }
  f.close();
}

// The controllers this hub has met (hardware address, last address, name) are kept in KNOWN_FILE,
// so after a restart it goes straight back to them. Before 0.9.3 it had to find each one again by
// asking the network, which took minutes and missed any that were powered off at the time.
#define KNOWN_FILE "/known.json"
static volatile bool knownDirty = false;
static void loadKnown() {
  File f = LittleFS.open(KNOWN_FILE, "r");
  if (!f) return;
  JsonDocument d;
  if (!deserializeJson(d, f)) {
    for (JsonObject k : d.as<JsonArray>()) {
      String mac = k["mac"] | "", ip = k["ip"] | "";
      if (mac.isEmpty() || ip.isEmpty() || nCtrls >= MAX_CTRLS) continue;
      Controller& c = ctrls[nCtrls];
      c.mac = mac; c.ip = ip; c.name = k["name"] | "WLED"; c.login = loginFor(c.name);
      c.owned = isOwnedMac(mac);
      c.lock = xSemaphoreCreateMutex();
      // Taken as online until a check says otherwise, so one that's off gets reported as such.
      c.online = true; c.misses = 1; c.pollSoon = true;
      nCtrls = nCtrls + 1;
    }
  }
  f.close();
}
static void saveKnown() {                               // status task only
  JsonDocument d; JsonArray a = d.to<JsonArray>();
  xSemaphoreTake(ctrlMx, portMAX_DELAY);
  for (int i = 0; i < nCtrls; i++) {
    JsonObject k = a.add<JsonObject>(); k["mac"] = ctrls[i].mac; k["ip"] = ctrls[i].ip; k["name"] = ctrls[i].name;
  }
  xSemaphoreGive(ctrlMx);
  File f = LittleFS.open(KNOWN_FILE, "w");
  if (f) { serializeJson(d, f); f.close(); }
}

static int findCtrl(const String& login, String& ip) {
  int found = -1;
  xSemaphoreTake(ctrlMx, portMAX_DELAY);
  for (int i = 0; i < nCtrls; i++) if (ctrls[i].login == login && !ctrls[i].direct && ctrls[i].owned) { found = i; ip = ctrls[i].ip; break; }
  xSemaphoreGive(ctrlMx);
  return found;
}

