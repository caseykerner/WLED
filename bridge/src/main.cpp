// Runs in the main task (from mqtt.loop()): collects a request's parts, then hands it to a worker.
static void onTunnel(const String& login, uint8_t* payload, unsigned int len) {
  unsigned int nl = 0;
  while (nl < len && payload[nl] != '\n') nl++;
  if (nl >= len) { tunRefused++; return; }
  JsonDocument h;
  if (deserializeJson(h, (const char*)payload, nl)) { tunRefused++; return; }
  String id = h["id"] | "";
  if (id.isEmpty()) { tunRefused++; return; }
  int part = h["i"] | 0, parts = h["n"] | 1;
  TunReq* r = nullptr;
  for (auto& x : tunIn) if (x.id == id) r = &x;
  if (!r) {
    if (part != 0) { tunRefused++; return; }
    tunIn.push_back(TunReq()); r = &tunIn.back();
    r->id = id; r->reply = h["c"] | ""; r->login = login; r->method = h["m"] | "GET";
    r->path = h["p"] | "/"; r->ct = h["ct"] | ""; r->parts = parts < 1 ? 1 : parts; r->started = millis();
    r->zip = h["z"] | false;
  }
  if (part != r->got || r->body.size() + (len - nl - 1) > TUN_MAX_BODY) r->bad = true;
  else r->body.append((const char*)payload + nl + 1, len - nl - 1);
  r->got++;
  if (r->got >= r->parts) {
    Job* j = new Job; j->tunnel = true; j->req = *r; j->req.queued = millis();
    for (size_t i = 0; i < tunIn.size(); i++) if (tunIn[i].id == id) { tunIn.erase(tunIn.begin() + i); break; }
    if (xQueueSend(jobQ, &j, 0) != pdTRUE) {           // all workers busy and the queue full
      Out* o = new Out; o->tunnel = true; o->topic = ("hg/resp/" + j->req.reply).c_str(); o->id = j->req.id; o->status = 503;
      delete j; post(o);
    }
  }
}

static void postBatchReply(std::shared_ptr<Batch> b) {
  STAGE(302);
  playsDone++;
  int n = std::count(b->results.begin(), b->results.end(), ':');
  int ok = 0; for (size_t p = b->results.find(":200"); p != std::string::npos; p = b->results.find(":200", p + 1)) ok++;
  hubEvent(String("Look sent to ") + String(n) + (n == 1 ? " controller" : " controllers") + " in " + String(millis() - b->started) + " ms" +
           (ok < n ? " (" + String(n - ok) + " didn't answer)" : "") + (b->done ? " (from home)" : ""));
  if (b->done) {                           // the home-network caller is waiting for it
    if (b->results.size() > 1 && b->results.back() == ',') b->results.pop_back();
    b->results += "}";
    xSemaphoreGive(b->done);
    return;
  }
  Out* o = new Out; o->tunnel = true; o->topic = ("hg/resp/" + b->reply).c_str(); o->id = b->id; o->status = 200;
  o->ct = "application/json";
  o->payload = b->results;
  if (o->payload.size() > 1 && o->payload.back() == ',') o->payload.pop_back();
  o->payload += "}";
  post(o);
}

static void batchDone(std::shared_ptr<Batch> b, const String& login, int code) {
  if (!b) return;
  STAGE(301);
  xSemaphoreTake(b->mx, portMAX_DELAY);
  b->results += "\"" + std::string(login.c_str()) + "\":" + std::to_string(code) + ",";
  bool last = --b->pending <= 0;
  xSemaphoreGive(b->mx);
  if (last) postBatchReply(b);
}

// Hub as master (main task): hg/<hub>/cmd carries looks for several controllers at once:
//   {"id":…,"c":<app client>,"z":true} \n <raw-deflate of {"jobs":[{"c":"house","b":{…}},…]}>
// Each controller gets its own look over the home network, all at the same time; the app gets
// one answer with every controller's result. Each look is remembered and checked (checkDesired).
static std::shared_ptr<Batch> onHubCommand(uint8_t* payload, unsigned int len) {
  STAGE(101);
  unsigned int nl = 0;
  while (nl < len && payload[nl] != '\n') nl++;
  if (nl >= len) { cmdsRefused++; return nullptr; }
  JsonDocument h;
  if (deserializeJson(h, (const char*)payload, nl)) { cmdsRefused++; return nullptr; }
  STAGE(102);
  // The owner's "Allow updates" from the app (only possible through AWS, never from /hub/play).
  if ((h["unlock"] | false) && !(h["local"] | false)) {
    unlockUntil = millis() + 10UL * 60 * 1000; if (!unlockUntil) unlockUntil = 1;
    hubEvent("Updates allowed for 10 minutes");
    statsDirty = true;
    Out* o = new Out; o->tunnel = true; o->topic = ("hg/resp/" + String((const char*)(h["c"] | ""))).c_str();
    o->id = (const char*)(h["id"] | ""); o->status = 200; o->ct = "application/json"; o->payload = "{\"unlocked\":600}";
    post(o);
    return nullptr;
  }
  // The owner's list of this hub's controllers, from the app (only through AWS): {"own":[mac,…]}.
  if (h["own"].is<JsonArray>() && !(h["local"] | false)) {
    JsonDocument keep; JsonArray macs = keep["macs"].to<JsonArray>();
    xSemaphoreTake(ctrlMx, portMAX_DELAY);
    ownedMacs.clear(); ownedListed = true;
    for (JsonVariant m : h["own"].as<JsonArray>()) { String mac = m.as<String>(); if (mac.length() && ownedMacs.size() < MAX_CTRLS) { ownedMacs.push_back(mac); macs.add(mac); } }
    int mine = 0;
    for (int i = 0; i < nCtrls; i++) {
      bool was = ctrls[i].owned;
      ctrls[i].owned = isOwnedMac(ctrls[i].mac);
      if (ctrls[i].owned) { mine++; if (!was) { ctrls[i].pollSoon = true; ctrls[i].stateHash = 0; } }
      else { ctrls[i].online = false; ctrls[i].desiredAt = 0; }
    }
    xSemaphoreGive(ctrlMx);
    File f = LittleFS.open(OWNED_FILE, "w");
    bool saved = false;
    if (f) { saved = serializeJson(keep, f) > 0; f.close(); }
    hubEvent(String("This hub now looks after ") + String((int)ownedMacs.size()) + (ownedMacs.size() == 1 ? " controller" : " controllers"));
    statsDirty = true;
    Out* o = new Out; o->tunnel = true; o->topic = ("hg/resp/" + String((const char*)(h["c"] | ""))).c_str();
    o->id = (const char*)(h["id"] | ""); o->status = saved ? 200 : 500; o->ct = "application/json";
    o->payload = "{\"owned\":" + std::to_string(ownedMacs.size()) + ",\"here\":" + std::to_string(mine) + "}";
    post(o);
    return nullptr;
  }
  auto b = std::make_shared<Batch>();
  b->id = h["id"] | ""; b->reply = h["c"] | ""; b->started = millis(); b->mx = xSemaphoreCreateMutex();
  if (h["local"] | false) b->done = xSemaphoreCreateBinary();
  const uint8_t* body = payload + nl + 1; size_t blen = len - nl - 1;
  char* plain = nullptr; size_t plen = blen;
  if (h["z"] | false) {
    const size_t cap = 300 * 1024;
    plain = (char*)ps_malloc(cap);
    if (!plain) { cmdsRefused++; return nullptr; }
    // The decompressor's ~11 KB state goes in PSRAM, not on the main task's 8 KB stack.
    tinfl_decompressor* d = (tinfl_decompressor*)ps_malloc(sizeof(tinfl_decompressor));
    if (!d) { free(plain); cmdsRefused++; return nullptr; }
    tinfl_init(d);
    STAGE(103);
    size_t inBytes = blen, n = cap;
    tinfl_status st = tinfl_decompress(d, body, &inBytes, (mz_uint8*)plain, (mz_uint8*)plain, &n,
                                       TINFL_FLAG_USING_NON_WRAPPING_OUTPUT_BUF);
    free(d);
    if (st != TINFL_STATUS_DONE) { free(plain); cmdsRefused++; return nullptr; }
    plen = n;
  }
  STAGE(104);
  JsonDocument doc(&spiAlloc);
  DeserializationError e = deserializeJson(doc, plain ? (const char*)plain : (const char*)body, plen);
  STAGE(105);
  if (plain) free(plain);
  if (e) { cmdsRefused++; return nullptr; }
  JsonArray jobs = doc["jobs"].as<JsonArray>();
  b->pending = jobs.size();
  if (b->pending == 0) { postBatchReply(b); return b; }
  for (JsonObject job : jobs) {
    STAGE(106);
    String login = job["c"] | "";
    String ip;
    int idx = findCtrl(login, ip);
    if (idx < 0 || ip.isEmpty()) { batchDone(b, login, 404); continue; }
    std::string look; serializeJson(job["b"], look);
    STAGE(107);
    String sig = job["b"]["seg"].is<JsonArray>() ? lookSig(job["b"]["seg"].as<JsonArrayConst>()) : String("");
    Controller& c = ctrls[idx];
    xSemaphoreTake(ctrlMx, portMAX_DELAY);
    if (sig.length()) { c.desiredBody = look; c.desiredSig = sig; c.desiredAt = millis(); c.desiredTries = 0; c.desiredOk = false; }
    else { c.desiredAt = 0; c.desiredBody.clear(); }      // on/off or brightness only: nothing to keep checking
    xSemaphoreGive(ctrlMx);
    cmdsIn++;
    STAGE(108);
    if (!enqueuePlay(login, look, b)) batchDone(b, login, 503);
  }
  STAGE(109);
  return b;
}

// Hub commands are unpacked in their own task: inflating a batch needs far more stack than the
// main loop's 8 KB (0.4.0 crashed in the decompressor on a real 4-controller look).
static QueueHandle_t hubQ;
static void hubTask(void*) {
  for (;;) {
    std::string* m = nullptr;
    if (xQueueReceive(hubQ, &m, portMAX_DELAY) != pdTRUE || !m) continue;
    onHubCommand((uint8_t*)m->data(), m->size());
    delete m;
  }
}
static void queueHubCommand(const uint8_t* payload, size_t len) {
  std::string* m = new std::string((const char*)payload, len);
  if (xQueueSend(hubQ, &m, 0) != pdTRUE) { delete m; cmdsRefused++; }
}

static void onMessage(char* topic, uint8_t* payload, unsigned int len) {
  String t(topic);
  if (t.startsWith("hg/req/")) { onTunnel(t.substring(7), payload, len); return; }
  if (cloudId.length() && t == "hg/" + cloudId + "/cmd") { queueHubCommand(payload, len); return; }
  if (t == "hg/applog/cmd") {                // the app's diagnostics timeline, for /log
    String all((const char*)payload, len);
    int from = 0;
    while (from < (int)all.length()) {
      int nl = all.indexOf('\n', from); if (nl < 0) nl = all.length();
      appLog.push_back(String(millis() / 1000) + " | " + all.substring(from, nl));
      from = nl + 1;
    }
    while (appLog.size() > 400) appLog.erase(appLog.begin());
    return;
  }
  cmdsIn++;
  int a = t.indexOf('/'), b = t.lastIndexOf('/');    // hg/<login>/cmd
  if (a < 0 || b <= a || len == 0 || len > MAX_CMD) { cmdsRefused++; return; }
  Job* j = new Job; j->tunnel = false; j->login = t.substring(a + 1, b); j->body = String((const char*)payload, len);
  if (xQueueSend(jobQ, &j, 0) != pdTRUE) { cmdsRefused++; delete j; }
}

// An everyday command (hg/<login>/cmd): only light-control keys are passed on.
static void runCommand(const Job& j) {
  String ip;
  int idx = findCtrl(j.login, ip);
  if (idx < 0 || ip.isEmpty()) { cmdsRefused++; return; }
  JsonDocument doc;
  if (deserializeJson(doc, j.body) || !doc.is<JsonObject>()) { cmdsRefused++; return; }
  JsonObject root = doc.as<JsonObject>();
  std::vector<String> drop;
  for (JsonPair kv : root) if (!allowedKey(kv.key().c_str())) drop.push_back(kv.key().c_str());
  for (auto& k : drop) root.remove(k);
  auto cleanSeg = [](JsonObject s) {
    std::vector<String> d;
    for (JsonPair kv : s) if (!allowedSegKey(kv.key().c_str())) d.push_back(kv.key().c_str());
    for (auto& k : d) s.remove(k);
  };
  if (root["seg"].is<JsonArray>()) for (JsonObject s : root["seg"].as<JsonArray>()) cleanSeg(s);
  else if (root["seg"].is<JsonObject>()) cleanSeg(root["seg"].as<JsonObject>());
  if (root.size() == 0) { cmdsRefused++; return; }
  std::string body; serializeJson(root, body);
  std::string out;
  xSemaphoreTake(ctrls[idx].lock, pdMS_TO_TICKS(10000));
  int code = wledRequest(ip, "POST", "/json/state", body, "application/json", out, nullptr, 2500, 4000);
  xSemaphoreGive(ctrls[idx].lock);
  if (code == 200) cmdsSent++; else cmdsRefused++;
  ctrls[idx].pollSoon = true;              // report the new state right away
}

// What the tunnel passes on. The app needs to read and write looks, schedules, zones and light
// settings; it never needs Wi-Fi, network, access-point, firmware or password settings.
static bool tunAllowed(TunReq& r) {
  String p = r.path, bare = p;
  int q = bare.indexOf('?'); if (q >= 0) bare = bare.substring(0, q);
  String lower = p; lower.toLowerCase();
  // Whole page names, not words inside them ("presets" contains "reset").
  String bl = bare; bl.toLowerCase();
  if (bl.startsWith("/update") || bl.startsWith("/reset") || bl.startsWith("/settings") || bl.startsWith("/upload/") ||
      bl.indexOf("wsec") >= 0 || bl.endsWith("sec.json") || lower.indexOf("..") >= 0) return false;
  if (r.method == "GET") {
    if (bare.startsWith("/json")) return true;
    if (bare.endsWith(".json") && lower.indexOf("cfg") < 0) return true;
    if (bare == "/edit") {
      if (lower.indexOf("list=") >= 0) return true;
      if (lower.indexOf("func=delete") >= 0 && lower.indexOf(".json") >= 0 && lower.indexOf("cfg") < 0) return true;
    }
    return false;
  }
  if (r.method == "DELETE") return bare == "/edit" && lower.indexOf("cfg") < 0 &&
                                   String(r.body.c_str()).indexOf(".json") >= 0 && String(r.body.c_str()).indexOf("cfg") < 0;
  if (r.method != "POST") return false;
  if (bare == "/json/state" || bare == "/json/si" || bare == "/json") return true;
  if (bare == "/json/cfg") {                 // light settings yes; network, Wi-Fi, AP and update settings never
    JsonDocument d;
    if (deserializeJson(d, r.body)) return false;
    const char* blocked[] = {"nw", "ap", "eth", "ota", "wifi"};
    for (const char* k : blocked) d.remove(k);
    r.body.clear();
    serializeJson(d, r.body);
    return true;
  }
  if (bare == "/upload") {                   // only HomeGlow's own data files
    String b = String(r.body.substr(0, 600).c_str());
    int f = b.indexOf("filename=\"");
    if (f < 0) return false;
    int e = b.indexOf('"', f + 10);
    String name = b.substring(f + 10, e); name.toLowerCase();
    return name.endsWith(".json") && name.indexOf("cfg") < 0 && name.indexOf("sec") < 0;
  }
  return false;
}


static void runTunnel(TunReq& r) {
  uint32_t t0 = millis();
  uint32_t wait = t0 - r.queued;
  Out* o = new Out; o->tunnel = true; o->topic = ("hg/resp/" + r.reply).c_str(); o->id = r.id;
  String ip;
  int idx = findCtrl(r.login, ip);
  if (r.bad || idx < 0 || ip.isEmpty()) {
    tunRefused++; noteRefused(r.method + " " + r.login + r.path + (r.bad ? " (parts)" : " (unknown controller)"));
    o->status = r.bad ? 413 : 404; post(o); return;
  }
  if (!tunAllowed(r)) { tunRefused++; noteRefused(r.method + " " + r.login + r.path); o->status = 403; post(o); return; }
  if (xSemaphoreTake(ctrls[idx].lock, pdMS_TO_TICKS(20000)) != pdTRUE) { o->status = 503; post(o); return; }
  uint32_t w0 = millis();
  String ct;
  int code = wledRequest(ip, r.method, r.path, r.body, r.ct, o->payload, &ct,
                         3000, r.body.size() > 20000 ? 30000 : 8000);
  uint32_t wledMs = millis() - w0;
  xSemaphoreGive(ctrls[idx].lock);
  o->status = code > 0 ? code : 504; o->ct = ct;
  if (r.zip && o->payload.size() >= ZIP_MIN) {
    std::string z = deflate(o->payload);
    if (!z.empty() && z.size() < o->payload.size()) { zipSaved += o->payload.size() - z.size(); o->payload.swap(z); o->zip = true; }
  }
  if (r.method != "GET") {
    ctrls[idx].pollSoon = true;
    // Something else changed this controller through the app: stop holding it to the last look.
    // Only a new look or a preset ends it: the app's follow-ups (brightness, sync settings a few
    // seconds after a look) left the hub holding nothing in 0.4.3.
    bool newLook = r.body.find("\"seg\"") != std::string::npos || r.body.find("\"ps\"") != std::string::npos ||
                   r.body.find("\"pl\"") != std::string::npos;
    if (newLook && (r.path.startsWith("/json/state") || r.path.startsWith("/json/si"))) {
      xSemaphoreTake(ctrlMx, portMAX_DELAY); ctrls[idx].desiredAt = 0; xSemaphoreGive(ctrlMx);
    }
  }
  tunDone++;
  uint32_t ms = millis() - r.started;
  xSemaphoreTake(ctrlMx, portMAX_DELAY);
  tunRecent.push_back(String(millis() / 1000) + "s " + r.method + " " + r.login + r.path.substring(0, 60) + " " + String(ms) + "ms " +
                      String((uint32_t)o->payload.size()) + (o->zip ? "z" : "") + (r.zip ? "" : " noz"));
  if (tunRecent.size() > 150) tunRecent.erase(tunRecent.begin());
  xSemaphoreGive(ctrlMx);
  tunMsTotal += ms; wledMsTotal += wledMs; waitMsTotal += wait;
  if (ms > tunMsMax) tunMsMax = ms;
  post(o);
}

// Hub as master: one controller's look from a batch (or a resend), sent over the home network.
static void runPlay(Job& j) {
  STAGE(201);
  String ip;
  int idx = findCtrl(j.login, ip);
  if (idx < 0 || ip.isEmpty()) { cmdsRefused++; batchDone(j.batch, j.login, 404); return; }
  uint32_t t0 = millis();
  std::string out;
  int code = 503;
  if (xSemaphoreTake(ctrls[idx].lock, pdMS_TO_TICKS(15000)) == pdTRUE) {
    code = wledRequest(ip, "POST", "/json/state", j.look, "application/json", out, nullptr, 3000, 8000);
    xSemaphoreGive(ctrls[idx].lock);
  }
  STAGE(202);
  if (code == 200) cmdsSent++; else cmdsRefused++;
  ctrls[idx].pollSoon = true;              // check it took, and tell the app
  xSemaphoreTake(ctrlMx, portMAX_DELAY);
  tunRecent.push_back(String(millis() / 1000) + "s PLAY " + j.login + " " + String(code) + " " + String(millis() - t0) + "ms " +
                      String((uint32_t)j.look.size()) + "b" + (j.batch ? "" : " (resend)"));
  if (tunRecent.size() > 150) tunRecent.erase(tunRecent.begin());
  xSemaphoreGive(ctrlMx);
  STAGE(203);
  batchDone(j.batch, j.login, code > 0 ? code : 504);
  STAGE(204);
}

static void workerTask(void*) {
  for (;;) {
    Job* j = nullptr;
    if (xQueueReceive(jobQ, &j, portMAX_DELAY) != pdTRUE || !j) continue;
    if (j->tunnel) runTunnel(j->req); else if (j->play) runPlay(*j); else runCommand(*j);
    delete j;
  }
}

