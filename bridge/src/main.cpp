// The TLS socket can take only part of a large write; PubSubClient doesn't retry, and a short
// write breaks the MQTT stream (AWS then drops the connection). Write in small pieces until done.
static bool writeAll(const uint8_t* p, size_t n) {
  size_t off = 0;
  uint32_t t0 = millis();
  while (off < n && millis() - t0 < 15000) {
    size_t w = mqtt.write(p + off, std::min((size_t)1024, n - off));
    if (w == 0) { shortWrites++; delay(5); continue; }
    off += w;
  }
  return off == n;
}

static void publishTunnel(const Out& o) {
  const std::string& body = o.payload;
  int parts = body.empty() ? 1 : (int)((body.size() + TUN_PART - 1) / TUN_PART);
  for (int i = 0; i < parts; i++) {
    JsonDocument h;
    h["id"] = o.id; h["s"] = o.status; h["i"] = i; h["n"] = parts;
    if (i == 0 && o.ct.length()) h["ct"] = o.ct;
    if (o.zip) h["z"] = 1;
    String head; serializeJson(h, head); head += '\n';
    size_t off = (size_t)i * TUN_PART, n = body.empty() ? 0 : std::min((size_t)TUN_PART, body.size() - off);
    if (!mqtt.beginPublish(o.topic.c_str(), head.length() + n, false)) return;
    if (!writeAll((const uint8_t*)head.c_str(), head.length())) return;
    if (n && !writeAll((const uint8_t*)body.data() + off, n)) return;
    mqtt.endPublish();
    mqtt.loop();
  }
}

static void publishOut(const Out& o) {
  if (o.tunnel) { publishTunnel(o); published++; return; }
  if (!mqtt.beginPublish(o.topic.c_str(), o.payload.size(), o.retained)) return;
  if (!writeAll((const uint8_t*)o.payload.data(), o.payload.size())) return;
  mqtt.endPublish();
  published++;
}

static void connectCloud() {
  lastTry = millis();
  led(0, 40, 40);
  mqtt.setServer(cloudEndpoint.c_str(), 8883);
  tls.setHandshakeTimeout(20);             // seconds (default 120): a stalled handshake mustn't freeze the hub
  uint32_t t0 = millis();
  if (mqtt.connect(cloudId.c_str(), stateTopicSelf.c_str(), 1, true, "{\"online\":false}")) {
    connects++; lastMqttErr = 0;
    mqtt.subscribe("hg/+/cmd", 1);
    mqtt.subscribe("hg/req/+", 0);
    JsonDocument me; me["online"] = true; me["ver"] = BRIDGE_VERSION; me["ip"] = WiFi.localIP().toString(); me["reset"] = resetReason;
    String s; serializeJson(me, s);
    mqtt.publish(stateTopicSelf.c_str(), s.c_str(), true);
    for (int i = 0; i < nCtrls; i++) { ctrls[i].pollSoon = true; ctrls[i].stateHash = 0; }
    led(0, 12, 0);
    Serial.printf("[cloud] connected in %u ms\n", (unsigned)(millis() - t0));
  } else {
    lastMqttErr = mqtt.state();
    led(40, 0, 0);
    char why[96] = ""; tls.lastError(why, sizeof why);
    Serial.printf("[cloud] failed (%d) after %u ms: %s\n", lastMqttErr, (unsigned)(millis() - t0), why);
  }
}

